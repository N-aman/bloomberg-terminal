/**
 * Fetches multi-year fundamental statements for any corporation.
 *
 * Lookup order:
 *  1. High-fidelity institutional registry (FALLBACK_FUNDAMENTALS)
 *  2. Live SEC EDGAR XBRL company facts API (EDGAR returns name + CIK,
 *     but financial line items are not yet parsed from raw XBRL â€” returns unavailable)
 *  3. unavailable: true  â€” no synthetic/hash-derived numbers are ever shown
 */
export async function fetchCompanyFundamentals(ticker: string, signal?: AbortSignal): Promise<CompanyFundamentals> {
  const sym = ticker.trim().toUpperCase();

  // 1. Direct hit in high-fidelity institutional store
  if (FALLBACK_FUNDAMENTALS[sym]) {
    return { ...FALLBACK_FUNDAMENTALS[sym], stale: false };
  }

  const cikInfo = await lookupCik(sym);
  const cik = cikInfo?.cik ?? "";
  const name = cikInfo?.name ?? `${sym}`;

  // 2. Try SEC EDGAR Company Facts API if CIK was found
  let edgarName = name;
  let edgarCik = cik;
  if (cik) {
    try {
      const paddedCik = cik.padStart(10, "0");
      const res = await fetch(
        `https://data.sec.gov/api/xbrl/companyfacts/CIK${paddedCik}.json`,
        {
          headers: {
            "User-Agent": "BloombergTerminal/1.0 (contact@bloomberg-terminal.dev)",
            Accept: "application/json",
          },
          signal,
        }
      );
      if (res.ok) {
        const data = await res.json();
        if (data.entityName) edgarName = data.entityName;
        if (data.cik) edgarCik = String(data.cik).padStart(10, "0");
      }
    } catch {
      // EDGAR unreachable — still return unavailable below
    }
  }

  // 3. No data available — tell the panel to show an unavailable message
  return {
    ticker: sym,
    name: edgarName || sym,
    cik: edgarCik,
    currency: "USD",
    marketCap: 0,
    peRatio: 0,
    periods: [],
    unavailable: true,
  };
}
